# ---------------------------------------------------------------- helpers

def write_text(rel: str, text: str) -> None:
    p = FILES / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text.strip() + "\n", encoding="utf-8", newline="\n")


def write_ref(name: str, obj) -> None:
    REF.mkdir(parents=True, exist_ok=True)
    (REF / name).write_text(json.dumps(obj, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")


def new_book():
    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    wb.properties.creator = "SDAIA Academy LDS-DMG-206"
    wb.properties.created = FIXED
    wb.properties.modified = FIXED
    wb.properties.lastModifiedBy = "SDAIA Academy LDS-DMG-206"
    return wb


def sheet(wb, title, header, rows, widths=None, fill_cols=(), rtl=True):
    ws = wb.create_sheet(title)
    ws.sheet_view.rightToLeft = rtl
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = HEAD_FILL
        c.alignment = Alignment(wrap_text=True, vertical="top")
    for r in rows:
        ws.append(list(r))
    for i, w in enumerate(widths or [], start=1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    for col in fill_cols:
        for row in range(2, ws.max_row + 1):
            ws.cell(row=row, column=col).fill = FILL_FILL
    ws.freeze_panes = "A2"
    return ws


def save(wb, rel: str, folder: Path = FILES) -> None:
    """Save with fixed zip entry dates, so the bytes are the same on every run."""
    import io
    import zipfile
    p = folder / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    buf = io.BytesIO()
    wb.save(buf)
    src = zipfile.ZipFile(io.BytesIO(buf.getvalue()))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for info in src.infolist():
            zi = zipfile.ZipInfo(info.filename, date_time=(2027, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            data = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                data = re.sub(rb"<dcterms:modified([^>]*)>[^<]*<", rb"<dcterms:modified\1>2027-01-01T00:00:00Z<", data)
            z.writestr(zi, data)
    p.write_bytes(out.getvalue())


def dropdown(ws, col_letter, values, rows):
    dv = DataValidation(type="list", formula1='"' + ",".join(values) + '"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"{col_letter}2:{col_letter}{rows + 1}")


